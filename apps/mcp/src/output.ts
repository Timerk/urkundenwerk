import { lstat, mkdir, realpath, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { ToolError } from "./errors";

function isInside(root: string, target: string): boolean {
  const path = relative(root, target);
  return (
    path === "" ||
    (!path.startsWith(`..${sep}`) && path !== ".." && !isAbsolute(path))
  );
}

async function existingAncestor(path: string): Promise<string> {
  let current = path;
  while (
    !(await lstat(current).then(
      () => true,
      () => false,
    ))
  ) {
    const parent = dirname(current);
    if (parent === current) return current;
    current = parent;
  }
  return current;
}

/**
 * Writes an export below the configured root. `subdirectory` is relative to
 * the root; absolute paths, `..` segments, and symlinks that lead outside
 * the root are refused. The filename is generated by the server and cannot
 * contain separators. Existing files are kept unless `overwrite` is set.
 */
export async function writeExport(
  root: string | undefined,
  subdirectory: string,
  filename: string,
  bytes: Uint8Array,
  overwrite: boolean,
): Promise<string> {
  if (!root) {
    throw new ToolError(
      "Saving to disk is off. Set URKUNDENWERK_EXPORT_DIR to an absolute directory in the MCP server's environment, or omit saveTo and use the embedded file.",
    );
  }
  if (isAbsolute(subdirectory) || /^[a-zA-Z]:/.test(subdirectory)) {
    throw new ToolError(
      'saveTo must be a path relative to the export directory, such as "." or "nord/2026".',
    );
  }
  if (/[\\/]/.test(filename) || filename.startsWith(".")) {
    throw new ToolError("The export filename is not safe to write.");
  }

  const realRoot = await realpath(root).catch(() => {
    throw new ToolError(
      "URKUNDENWERK_EXPORT_DIR does not exist. Create the directory or change the setting.",
    );
  });
  const target = resolve(realRoot, subdirectory);
  if (!isInside(realRoot, target)) {
    throw new ToolError("saveTo must stay inside the export directory.");
  }
  // A symlink inside the root could point elsewhere. Check the deepest
  // existing ancestor before creating directories, and the result after.
  if (!isInside(realRoot, await realpath(await existingAncestor(target)))) {
    throw new ToolError("saveTo must stay inside the export directory.");
  }
  await mkdir(target, { recursive: true });
  const realTarget = await realpath(target);
  if (!isInside(realRoot, realTarget)) {
    throw new ToolError("saveTo must stay inside the export directory.");
  }

  const file = join(realTarget, filename);
  const existing = await lstat(file).catch(() => undefined);
  if (existing?.isSymbolicLink()) {
    throw new ToolError(
      `${relative(realRoot, file)} is a symbolic link. Remove it or choose another saveTo directory.`,
    );
  }
  try {
    await writeFile(file, bytes, { flag: overwrite ? "w" : "wx" });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "EEXIST") {
      throw new ToolError(
        `${relative(realRoot, file)} already exists in the export directory. Pass overwrite: true to replace it.`,
      );
    }
    throw error;
  }
  return file;
}
